#ifndef CTAP_GET_INFO_H
#define CTAP_GET_INFO_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#define CTAP_GET_INFO_MAX_CBOR_SIZE 448U

/* Device metadata supplied by the application. AAGUID is stable per model;
 * the application supplies its model identity. max_message_size includes the
 * CTAP command byte and its CBOR data. */
typedef struct {
    uint8_t aaguid[16];
    uint32_t max_message_size;
    uint32_t firmware_version; /* Vendor revision; zero omits the optional field. */
    uint32_t remaining_credentials; /* Free shared slots; refreshed before GetInfo. */
    uint16_t max_credential_id_length; /* Zero selects the 32-byte stored-ID profile. */
    bool usb_transport; /* Supplied by the application; never inferred by the core. */
    bool user_presence; /* Set only when a platform presence provider is connected. */
    bool ed25519; /* Complete Ed25519 credential provider bound. */
    bool make_credential; /* ES256 provider + UP configured; set by the backend. */
    bool hmac_secret; /* Complete secret provider bound; PIN protocols 1/2 key agreement. */
    bool pin_uv_auth; /* Complete PIN/token + credential protection configured. */
    uint8_t min_pin_length; /* Zero means default four. */
    bool always_uv, force_pin_change;
    bool pin_set; /* Current persistent PIN state, refreshed before GetInfo. */
    bool large_blobs;
    bool resident_credentials; /* Complete discovery + credential management binding. */
} CtapGetInfoProfile;

/* Encode the GetInfo map only (without status byte or HID framing). Returns
 * false for incomplete profiles (credentials, hmac-secret and UP are required),
 * invalid output or insufficient capacity; failure leaves
 * output and output_length unchanged. Storage must not overlap the profile.
 *
 * CTAP 2.3 section 6.4: versions, aaguid, options, maxMsgSize. Options currently
 * report up=profile.user_presence and plat=false. Complete resident_credentials
 * enables rk=true and credMgmt=true; other bindings keep rk=false. With MakeCredential
 * configured, advertise ES256 (and Ed25519 when bound) and packed self-attestation (none is implicit),
 * and makeCredUvNotRqd reflects the always-UV policy. hmac-secret adds extensions and pinUvAuthProtocols=[2,1]
 * for key agreement, plus hmac-secret-mc when MakeCredential is configured.
 * pin_uv_auth adds credProtect and pinUvAuthToken=true;
 * clientPin reflects pin_set, minPINLength and forcePINChange reflect policy.
 * authnrCfg/alwaysUv/setMinPINLength are available with the PIN binding. No RP
 * minimum-length disclosure list is supported. Resident bindings add credBlob;
 * largeBlobs/largeBlobKey are advertised only with a complete blob-store binding.
 * Built-in uv remains omitted.
 * Credential IDs generated by the current handlers are 32 bytes. USB transport
 * and vendor firmware revision are reported only when supplied by the application.
 * Resident profiles report remainingDiscoverableCredentials from remaining_credentials.
 * Advertise FIDO_2_0/2.1 discovery alongside the FIDO_2_3 development target;
 * full authenticator conformance has not been established.
 */
bool ctap_get_info_encode(const CtapGetInfoProfile *profile,
    uint8_t *output, size_t capacity, size_t *output_length);

#endif
